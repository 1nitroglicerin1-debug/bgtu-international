def main():
    with open(SRC, encoding="utf-8") as f:
        data = json.load(f)

    for direction in data["directions"]:
        m = META[direction["slug"]]
        direction["icon"] = m["icon"]
        if direction["slug"] == "fit":
            direction["short"] = "ФИТБ"
            direction["title"] = "Факультет информационных технологий"
        for s in direction["specialties"]:
            s["direction"] = direction["slug"]
            s["directionTitle"] = direction["title"]
            s["directionShort"] = direction["short"]
            s["directionColor"] = direction["color"]
            s["directionIcon"] = m["icon"]
            s["meta"] = {"pros": m["pros"], "who": m["who"], "modules": m["modules"]}

    js = "window.BGTU_DATA = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
    with open(DST, "w", encoding="utf-8") as f:
        f.write(js)

    total = sum(len(d["specialties"]) for d in data["directions"])
    print(f"OK: {len(data['directions'])} направлений, {total} специальностей -> {os.path.basename(DST)}")

if __name__ == "__main__":
    main()
